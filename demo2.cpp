// Демонстрационная программа для класса CHAIN (вариант 7)
// Задача: построить цепочку из n динамических переменных, содержащих
// вводимые вещественные числа. Между [n/2]-й и ([n/2]+1)-й переменной
// вставить переменную со значением 0.
#include "lab2.h"
#include <iostream>

using namespace std;

namespace Lab2 {

	void Run()
	{
		int n;
		int choice;

		cout << "Демонстрационная программа: цепочка динамических переменных (класс CHAIN)." << endl;
		cout << "Программа строит цепочку из n вводимых вещественных чисел и" << endl;
		cout << "вставляет между [n/2]-й и ([n/2]+1)-й переменной значение 0." << endl;
		cout << endl;

		do
		{
			cout << "Введите количество чисел цепочки n (целое число, n > 0): ";
			while (!(cin >> n) || n <= 0)
			{
				cin.clear();
				cin.ignore(10000, '\n');
				cout << "Некорректное значение! Введите целое положительное число n: ";
			}

			CHAIN chain(n); // создаём цепочку и вводим n чисел с клавиатуры

			cout << endl << "Цепочка до вставки нуля:" << endl;
			chain.Print();

			chain.InsertZero();

			cout << endl << "Цепочка после вставки нуля между " << (n / 2)
				<< "-м и " << (n / 2 + 1) << "-м элементом:" << endl;
			chain.Print();

			cout << endl << "Итоговое количество элементов цепочки: " << chain.GetCount() << endl;

			// (Доп. задание) даём пользователю вставлять 0 на любую позицию
			// по его выбору, сколько угодно раз подряд
			int insertMore;
			cout << endl << "Вставить ещё один 0 на выбранную вами позицию? (1 - да, 0 - нет): ";
			cin >> insertMore;
			while (insertMore == 1)
			{
				int index;
				cout << "Введите позицию (номер элемента, считая с 1), на которую вставить 0: ";
				while (!(cin >> index))
				{
					cin.clear();
					cin.ignore(10000, '\n');
					cout << "Некорректное значение! Введите целое число: ";
				}

				chain.InsertZeroAt(index);

				cout << endl << "Цепочка после вставки 0 на позицию " << index << ":" << endl;
				chain.Print();
				cout << "Текущее количество элементов цепочки: " << chain.GetCount() << endl;

				cout << endl << "Вставить ещё один 0? (1 - да, 0 - нет): ";
				cin >> insertMore;
			}

			cout << endl << "Построить ещё одну цепочку? (1 - да, 0 - нет): ";
			cin >> choice;
			cout << endl;
		} while (choice != 0);

		cout << "Завершение работы программы." << endl;
		return;
	}
}