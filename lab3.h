//    в последовательности из N чисел.

namespace Lab3 {

	// а) Цепочка динамических переменных (та же задача, что в ЛР 2, вариант 7),
	//    но экземпляры звеньев теперь создаются/удаляются через new/delete.
	class CHAIN
	{
	public:
		CHAIN(int n); // конструктор: создаёт цепочку из n динамических переменных (new), значения вводятся с клавиатуры
		void Print();          // печать всех значений цепочки в порядке их следования
		void InsertZero();     // вставка переменной со значением 0 между [n/2]-м и ([n/2]+1)-м элементом
		int GetCount();        // возвращает текущее количество элементов цепочки
		~CHAIN();              // деструктор: удаляет (delete) все динамические переменные цепочки

	private:
		// Структура одного звена цепочки — динамической переменной
		struct Node
		{
			float value;  // хранимое вещественное число
			Node* next;   // указатель на следующее звено цепочки (NULL, если звено последнее)
		};

		Node* head;   // указатель на первое звено цепочки
		int n;        // исходное количество введённых чисел (без учёта вставленного нуля)
		int count;    // текущее количество звеньев цепочки
	};

	// б) Вариант 10: динамический массив вещественных чисел; подсчитать
	//    количество совпадающих элементов в последовательности из N чисел.
	class DUPARRAY
	{
	public:
		DUPARRAY(int n); // конструктор: создаёт динамический массив из n вещественных чисел (new[]), значения вводятся с клавиатуры
		void Print();           // печать всех элементов массива
		int CountMatches();     // подсчёт количества элементов, у которых в массиве есть хотя бы одно совпадение (дубликат)
		~DUPARRAY();            // деструктор: освобождает память массива (delete[])

	private:
		float* data; // указатель на динамический массив вещественных чисел
		int n;       // количество элементов массива
	};
}