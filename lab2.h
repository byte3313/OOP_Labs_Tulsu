// Описание класса CHAIN — цепочка динамических переменных (вещественных чисел)
// Вариант 7: построить цепочку из n вводимых вещественных чисел;
// между [n/2]-м и ([n/2]+1)-м элементом вставить переменную со значением 0.

namespace Lab2 {

	class CHAIN
	{
	public:
		CHAIN(int n); // конструктор: создаёт цепочку из n динамических переменных, значения которых вводятся с клавиатуры
		void Print();          // печать всех значений цепочки в порядке их следования
		void InsertZero();     // вставка переменной со значением 0 между [n/2]-м и ([n/2]+1)-м элементом
		void InsertZeroAt(int index); // (доп. задание к защите) вставка 0 на произвольную позицию index, указанную пользователем; можно вызывать несколько раз подряд
		int GetCount();        // возвращает текущее количество элементов цепочки
		~CHAIN();              // деструктор: освобождает память всех динамических переменных цепочки

	private:
		// Структура одного звена цепочки — динамической переменной
		struct Node
		{
			float value;  // хранимое вещественное число
			Node* next;   // указатель на следующее звено цепочки (NULL, если звено последнее)
		};

		Node* head;   // указатель на первое звено цепочки
		int n;        // исходное количество введённых чисел (без учёта вставленного нуля)
		int count;    // текущее количество звеньев цепочки
	};
}