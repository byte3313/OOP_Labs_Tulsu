// Демонстрационная программа для лабораторной работы 3 (вариант 10)
// а) CHAIN — цепочка динамических переменных (та же задача, что в ЛР 2,
//    вариант 7), созданная и удаляемая операторами new/delete.
// б) DUPARRAY — подсчёт количества совпадающих элементов в
//    последовательности из N вещественных чисел (динамический массив, new/delete[]).
#include "lab3.h"
#include <iostream>

using namespace std;

namespace Lab3 {

	void Run()
	{
		int menu;
		int choice;

		cout << "Демонстрационная программа к лабораторной работе №3 (вариант 10)." << endl;
		cout << "Доступные задания:" << endl;
		cout << "  1 - цепочка динамических переменных (задание а, new/delete);" << endl;
		cout << "  2 - подсчёт совпадающих элементов в последовательности чисел (задание б);" << endl;
		cout << "  0 - выход из программы." << endl;
		cout << endl;

		do
		{
			cout << "Введите номер задания (0-2): ";
			if (!(cin >> menu))
			{
				cin.clear();
				cin.ignore(10000, '\n');
				cout << "Некорректный ввод!" << endl << endl;
				continue;
			}

			if (menu == 1)
			{
				int n;
				cout << "Введите количество чисел цепочки n (целое число, n > 0): ";
				while (!(cin >> n) || n <= 0)
				{
					cin.clear();
					cin.ignore(10000, '\n');
					cout << "Некорректное значение! Введите целое положительное число n: ";
				}

				CHAIN chain(n); // создаём цепочку (звенья — через new) и вводим n чисел

				cout << endl << "Цепочка до вставки нуля:" << endl;
				chain.Print();

				chain.InsertZero();

				cout << endl << "Цепочка после вставки нуля между " << (n / 2)
					<< "-м и " << (n / 2 + 1) << "-м элементом:" << endl;
				chain.Print();

				cout << endl << "Итоговое количество элементов цепочки: " << chain.GetCount() << endl;
				// Деструктор ~CHAIN() вызовется автоматически при выходе chain из области
				// видимости в конце итерации цикла — все звенья будут удалены оператором delete.
			}
			else if (menu == 2)
			{
				int n;
				cout << "Введите количество элементов последовательности n (целое число, n > 0): ";
				while (!(cin >> n) || n <= 0)
				{
					cin.clear();
					cin.ignore(10000, '\n');
					cout << "Некорректное значение! Введите целое положительное число n: ";
				}

				DUPARRAY arr(n); // создаём динамический массив (new[]) и вводим n чисел

				cout << endl << "Введённая последовательность чисел:" << endl;
				arr.Print();

				int matches = arr.CountMatches();
				cout << endl << "Количество совпадающих элементов (имеющих дубликат в последовательности): "
					<< matches << endl;
				// Деструктор ~DUPARRAY() вызовется автоматически при выходе arr из области
				// видимости — динамический массив будет освобождён оператором delete[].
			}
			else if (menu != 0)
			{
				cout << "Введено неверное значение! Допустимые значения: 0, 1, 2." << endl;
			}

			cout << endl << "Продолжить работу с программой? (1 - да, 0 - нет): ";
			cin >> choice;
			cout << endl;
		} while (choice != 0);

		cout << "Завершение работы программы." << endl;
		return;
	}
}